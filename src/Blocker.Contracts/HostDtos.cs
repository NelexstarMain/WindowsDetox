using System.Text.Json.Serialization;
using Blocker.Sdk.Events;
using Blocker.Sdk.Extensions;
using Blocker.Sdk.Model;

namespace Blocker.Contracts;

/// <summary>Version of the service/plugin-host protocol (the <c>host.*</c> and <c>pluginHost.*</c> methods).</summary>
public static class PluginHostProtocol
{
    /// <summary>Current protocol version.</summary>
    public const int Version = 1;
}

/// <summary>Result of <see cref="IpcMethods.PluginHostRegister"/>.</summary>
/// <param name="Accepted">Whether the service accepted the host.</param>
/// <param name="ProtocolVersion">Protocol version of the service.</param>
public sealed record PluginHostRegisterResponse(bool Accepted, int ProtocolVersion);

/// <summary>Notification <see cref="IpcMethods.PluginHostPluginFaulted"/>: a plugin's circuit breaker tripped.</summary>
/// <param name="PluginId">The faulted plugin.</param>
/// <param name="Reason">Why it faulted (generated by the host, not by the plugin).</param>
public sealed record PluginFaultedNotification(string PluginId, string Reason);

/// <summary>Notification <see cref="IpcMethods.PluginHostRenderRequested"/>: a contribution wants to be rendered again.</summary>
/// <param name="PluginId">Owning plugin.</param>
/// <param name="ContributionId">Contribution within the plugin.</param>
public sealed record RenderRequestedNotification(string PluginId, string ContributionId);

/// <summary>State of a plugin inside the host.</summary>
public enum HostPluginState
{
    /// <summary>Loaded and serving callbacks.</summary>
    Running,

    /// <summary>Its circuit breaker tripped; its contributions were removed.</summary>
    Faulted,

    /// <summary>It could not be loaded or initialized.</summary>
    Failed,
}

/// <summary>One plugin as reported by the host.</summary>
/// <param name="PluginId">Plugin id.</param>
/// <param name="Name">Display name, if the manifest could be read.</param>
/// <param name="Version">Version text, if the manifest could be read.</param>
/// <param name="State">Current state.</param>
/// <param name="Error">Why the plugin failed or faulted.</param>
public sealed record HostPluginStatusDto(string PluginId, string? Name, string? Version, HostPluginState State, string? Error);

/// <summary>Parameters of <see cref="IpcMethods.HostLoadPlugins"/>.</summary>
/// <param name="Session">Current session state, so plugins see it from their first callback.</param>
/// <param name="VerifiedUtcNow">Network-verified UTC time at the moment of sending; anchors the plugin clock.</param>
public sealed record LoadPluginsRequest(SessionStatusDto Session, DateTimeOffset VerifiedUtcNow);

/// <summary>Result of <see cref="IpcMethods.HostLoadPlugins"/>.</summary>
/// <param name="Plugins">Every enabled plugin and what became of it.</param>
public sealed record LoadPluginsResponse(IReadOnlyList<HostPluginStatusDto> Plugins);

/// <summary>Parameters of <see cref="IpcMethods.HostEvaluatePackage"/>.</summary>
/// <param name="PackageBase64">The plugin ZIP, base64 encoded.</param>
public sealed record EvaluatePackageRequest(string PackageBase64);

/// <summary>Stage at which an install evaluation ended; mirrors the Core pipeline plus <see cref="Host"/>.</summary>
public enum PluginInstallStageDto
{
    /// <summary>ZIP structure.</summary>
    Package,

    /// <summary><c>plugin.json</c> schema.</summary>
    Manifest,

    /// <summary>Static API policy.</summary>
    Policy,

    /// <summary>Compilation.</summary>
    Compile,

    /// <summary>Loading and entry type.</summary>
    Load,

    /// <summary>The plugin's own tests.</summary>
    Tests,

    /// <summary>Every stage passed.</summary>
    Ready,

    /// <summary>The evaluation host crashed, hung or could not be reached.</summary>
    Host,
}

/// <summary>Result of <see cref="IpcMethods.HostEvaluatePackage"/>.</summary>
/// <param name="Stage">Stage that failed, or <see cref="PluginInstallStageDto.Ready"/>.</param>
/// <param name="Errors">User-facing errors; empty on success.</param>
/// <param name="PluginId">Manifest id, once the manifest was parsed.</param>
/// <param name="Name">Manifest name.</param>
/// <param name="Version">Manifest version text.</param>
/// <param name="Author">Manifest author.</param>
/// <param name="Capabilities">Declared capability names.</param>
/// <param name="TestsPassed">Number of passed plugin tests.</param>
/// <param name="TestsTotal">Number of plugin tests that ran.</param>
/// <param name="Tests">Every test that ran; absent when the tests did not run.</param>
public sealed record PluginInstallReportDto(
    PluginInstallStageDto Stage,
    IReadOnlyList<string> Errors,
    string? PluginId,
    string? Name,
    string? Version,
    string? Author,
    IReadOnlyList<string> Capabilities,
    int TestsPassed,
    int TestsTotal,
    IReadOnlyList<PluginTestResultDto>? Tests = null)
{
    /// <summary>Gets whether the plugin passed every stage.</summary>
    [JsonIgnore]
    public bool Succeeded => Stage == PluginInstallStageDto.Ready;
}

/// <summary>Parameters of <see cref="IpcMethods.HostInterceptProcess"/>.</summary>
/// <param name="Process">The new process.</param>
public sealed record InterceptProcessRequest(ProcessDescriptor Process);

/// <summary>Parameters of <see cref="IpcMethods.HostInterceptWindow"/>; titles are stripped per plugin by the host.</summary>
/// <param name="Window">The newly activated window.</param>
public sealed record InterceptWindowRequest(WindowDescriptor Window);

/// <summary>Verdict of the interceptors. Plugins can only block; there is no allow verdict.</summary>
/// <param name="Block">Whether a plugin vetoed the process or window.</param>
/// <param name="Reason">User-visible reason when blocked.</param>
/// <param name="PluginId">The vetoing plugin.</param>
public sealed record InterceptResponse(bool Block, string? Reason, string? PluginId)
{
    /// <summary>Gets the response that leaves the decision to the core (also the fallback for every failure).</summary>
    public static InterceptResponse Abstain { get; } = new(false, null, null);
}

/// <summary>Parameters of <see cref="IpcMethods.HostEvaluateLock"/>.</summary>
/// <param name="Action">The voluntary action to vote on.</param>
public sealed record EvaluateLockRequest(LockAction Action);

/// <summary>One veto of a lock-policy contributor.</summary>
/// <param name="PluginId">The vetoing plugin.</param>
/// <param name="Reason">User-visible reason.</param>
public sealed record LockVetoDto(string PluginId, string Reason);

/// <summary>Result of <see cref="IpcMethods.HostEvaluateLock"/>; empty when nobody objects (also the fallback for every failure).</summary>
/// <param name="Vetoes">Vetoes in plugin id order.</param>
public sealed record EvaluateLockResponse(IReadOnlyList<LockVetoDto> Vetoes);

/// <summary>Parameters of <see cref="IpcMethods.HostInvokePluginMethod"/>.</summary>
/// <param name="PluginId">Owning plugin.</param>
/// <param name="Method">Plugin-local method name.</param>
/// <param name="PayloadJson">Request JSON, at most 64 KiB.</param>
public sealed record InvokePluginMethodRequest(string PluginId, string Method, string PayloadJson);

/// <summary>Result of <see cref="IpcMethods.HostInvokePluginMethod"/>.</summary>
/// <param name="PayloadJson">Response JSON, at most 64 KiB.</param>
public sealed record InvokePluginMethodResponse(string PayloadJson);

/// <summary>Parameters of <see cref="IpcMethods.HostSessionChanged"/>.</summary>
/// <param name="Status">New session state.</param>
/// <param name="VerifiedUtcNow">Network-verified UTC time at the moment of sending; re-anchors the plugin clock.</param>
public sealed record SessionChangedRequest(SessionStatusDto Status, DateTimeOffset VerifiedUtcNow);

/// <summary>Kind of a <see cref="HostEventDto"/>; custom plugin events never cross the process boundary.</summary>
public enum HostEventKind
{
    /// <summary><see cref="SessionStarted"/>.</summary>
    SessionStarted,

    /// <summary><see cref="SessionEnded"/>.</summary>
    SessionEnded,

    /// <summary><see cref="EmergencyPassStarted"/>.</summary>
    EmergencyPassStarted,

    /// <summary><see cref="EmergencyPassEnded"/>.</summary>
    EmergencyPassEnded,

    /// <summary><see cref="ProcessBlocked"/>.</summary>
    ProcessBlocked,

    /// <summary><see cref="ActiveWindowChanged"/>.</summary>
    ActiveWindowChanged,

    /// <summary><see cref="UserIdleChanged"/>.</summary>
    UserIdleChanged,
}

/// <summary>Flat wire form of the core events (<see cref="IBlockerEvent"/>); only the members of <paramref name="Kind"/> are set.</summary>
/// <param name="Kind">Which event this is.</param>
/// <param name="OccurredAt">Verified time of the event.</param>
/// <param name="SessionId">Session of the session and emergency-pass events.</param>
/// <param name="Seconds">Planned duration, pass duration or idle duration, in seconds.</param>
/// <param name="PassesLeftToday">Passes left after a started pass.</param>
/// <param name="EndReason">Why the session ended.</param>
/// <param name="Process">The blocked process.</param>
/// <param name="Reason">Why the process was blocked.</param>
/// <param name="BlockedByPlugin">Plugin whose interceptor vetoed the process.</param>
/// <param name="Window">The new foreground window.</param>
/// <param name="IsIdle">Whether the user just became idle.</param>
public sealed record HostEventDto(
    HostEventKind Kind,
    DateTimeOffset OccurredAt,
    Guid? SessionId = null,
    double? Seconds = null,
    int? PassesLeftToday = null,
    SessionEndReason? EndReason = null,
    ProcessDescriptor? Process = null,
    BlockReason? Reason = null,
    string? BlockedByPlugin = null,
    WindowDescriptor? Window = null,
    bool? IsIdle = null)
{
    private const double MaxSeconds = 366 * 24 * 3600.0;

    /// <summary>Converts a core event to its wire form.</summary>
    /// <param name="evt">The event.</param>
    /// <returns>The DTO, or <see langword="null"/> for events that must not cross the boundary (custom plugin events).</returns>
    public static HostEventDto? From(IBlockerEvent evt)
    {
        ArgumentNullException.ThrowIfNull(evt);
        return evt switch
        {
            SessionStarted e => new(HostEventKind.SessionStarted, e.OccurredAt, SessionId: e.SessionId, Seconds: e.PlannedDuration.TotalSeconds),
            SessionEnded e => new(HostEventKind.SessionEnded, e.OccurredAt, SessionId: e.SessionId, EndReason: e.Reason),
            EmergencyPassStarted e => new(HostEventKind.EmergencyPassStarted, e.OccurredAt, SessionId: e.SessionId, Seconds: e.Duration.TotalSeconds, PassesLeftToday: e.PassesLeftToday),
            EmergencyPassEnded e => new(HostEventKind.EmergencyPassEnded, e.OccurredAt, SessionId: e.SessionId),
            ProcessBlocked e => new(HostEventKind.ProcessBlocked, e.OccurredAt, Process: e.Process, Reason: e.Reason, BlockedByPlugin: e.BlockedByPlugin),
            ActiveWindowChanged e => new(HostEventKind.ActiveWindowChanged, e.OccurredAt, Window: e.Window),
            UserIdleChanged e => new(HostEventKind.UserIdleChanged, e.OccurredAt, Seconds: e.IdleDuration.TotalSeconds, IsIdle: e.IsIdle),
            _ => null,
        };
    }

    /// <summary>Converts the wire form back to a core event.</summary>
    /// <returns>The event, or <see langword="null"/> when members required by <see cref="Kind"/> are missing or out of range.</returns>
    public IBlockerEvent? ToEvent() => Kind switch
    {
        HostEventKind.SessionStarted when SessionId is { } id && Duration(Seconds) is { } d => new SessionStarted(id, d, OccurredAt),
        HostEventKind.SessionEnded when SessionId is { } id && EndReason is { } r => new SessionEnded(id, r, OccurredAt),
        HostEventKind.EmergencyPassStarted when SessionId is { } id && Duration(Seconds) is { } d && PassesLeftToday is { } left =>
            new EmergencyPassStarted(id, d, left, OccurredAt),
        HostEventKind.EmergencyPassEnded when SessionId is { } id => new EmergencyPassEnded(id, OccurredAt),
        HostEventKind.ProcessBlocked when Process is { } p && Reason is { } r => new ProcessBlocked(p, r, BlockedByPlugin, OccurredAt),
        HostEventKind.ActiveWindowChanged when Window is { } w => new ActiveWindowChanged(w, OccurredAt),
        HostEventKind.UserIdleChanged when IsIdle is { } idle && Duration(Seconds) is { } d => new UserIdleChanged(idle, d, OccurredAt),
        _ => null,
    };

    private static TimeSpan? Duration(double? seconds) =>
        seconds is { } s && double.IsFinite(s) && s is >= 0 and <= MaxSeconds ? TimeSpan.FromSeconds(s) : null;
}
